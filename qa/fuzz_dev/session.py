"""Part 2: interactive pty session (zsh + bash). Usage: python3 session.py"""
import sys, os, shutil, subprocess; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ptyd import *
HERE=os.path.dirname(os.path.abspath(__file__))
def setup(name):
    S=HERE+'/'+name; shutil.rmtree(S,ignore_errors=True); os.makedirs(S)
    subprocess.run([HERE+'/fixture.sh',S+'/fx'],capture_output=True,check=True); return S
LOG=[]
def run(shell):
    S=setup('s_'+shell); sh=Sh(shell,S+'/home',S+'/rh',S+'/fx/repo')
    def st(keys,t=2.5):
        sh.send(keys); o=clean(sh.read(t)); print(f'\n>>> [{shell}] {keys!r}\n{o}'); return o
    def rec(step,exp,act,ok): LOG.append((shell,step,exp,act,'PASS' if ok else 'FAIL')); print('### VERDICT',LOG[-1])
    if shell=='zsh':
        st('git stauts\n'); o=st('redo\n'); o2=st('\n')
        rec('typo `git stauts` -> redo -> Enter','`git status` on prompt, runs','prompt buffer: '+o.strip().splitlines()[-1][-30:], o.rstrip().endswith('git status') and 'On branch' in o2)
        st('echo ok\n'); o=st('redo\n')
        rec('redo after a successful cmd','say last cmd succeeded / not re-offer stale fix as new', 'shows "You ran: (just now) git stauts" again' if 'git stauts' in o else o[:80], 'git stauts' not in o or 'succeeded' in o)
        sh.send('\x03'); sh.read(1)
        o1=st('redo\n'); sh.send('\x03'); sh.read(1); o2=st('redo\n')
        rec('redo twice in a row','same fix both times, no error', 'identical' if o1.split('You ran')[-1][:200]==o2.split('You ran')[-1][:200] else 'differs', o1.split('You ran')[-1][:200]==o2.split('You ran')[-1][:200])
        o=st('\x03',1.5); o2=st('git rev-parse --abbrev-ref HEAD\n')
        rec('Ctrl-C on pushed fix','buffer discarded, nothing runs','fresh prompt, branch still main' if 'main' in o2 else o2[-80:], 'main' in o2)
        st('git checkout develpo\n'); o=st('redo\n'); o2=st('\n')
        rec('`git checkout develpo` -> redo -> Enter','git checkout develop',o.rstrip().splitlines()[-1][-40:]+' | '+('switched' if "Switched to branch 'develop'" in o2 else o2[-60:]), "Switched to branch 'develop'" in o2)
        st('git checkout -q main\n')
        st('git stauts \\\n',1); st('  -s\n'); o=st('redo\n'); o2=st('\n')
        rec('multi-line `git stauts \\ <nl> -s` -> redo','fix `git status -s` (or equivalent)', o.rstrip().splitlines()[-1][-40:], o.rstrip().endswith('git status -s') or o.rstrip().endswith('git status  -s'))
        st('make biuld\n'); st('make biuld\n'); o=st('redo\n'); o2=st('\n'); h=st('redo history\n')
        rec('command failing twice -> redo -> Enter','make build runs; history sensible', ('building' if 'building' in o2 else 'no build')+f"; history lines with 'make biuld': {h.count('make biuld')}", 'building' in o2)
        st('gti log --oneline -3\n'); o=st('redo -y\n',3)
        rec('`redo -y` on safe fix (gti log)','runs git log immediately', 'ran' if 'tweak' in o else o[-120:], 'tweak' in o)
        st('git branch -d feature/auth\n'); o=st('redo -y\n',3); sh.send('\x03'); sh.read(1); o2=st('git branch --list feature/auth\n')
        rec('`redo -y` on destructive fix (branch -d unmerged)','must NOT auto-run git branch -D', ('branch still exists' if 'feature/auth' in o2.split('--list feature/auth',1)[-1] else 'BRANCH DELETED')+' | '+o.strip().splitlines()[-1][-60:], 'feature/auth' in o2.split('--list feature/auth',1)[-1])
        sh.send('\x03'); sh.read(1)
        st('rm src\n'); o=st('redo -y\n',3); sh.send('\x03'); sh.read(1); o2=st('ls -d src\n')
        rec('`redo -y` on destructive fix (rm dir)','must NOT auto-run rm -r', ('src kept' if 'No such' not in o2 else 'SRC DELETED')+' | '+o.strip().splitlines()[-1][-60:], 'No such' not in o2)
        sh.send('\x03'); sh.read(1)
        st("redo run 'git sta'\n"); o=st('redo\n',3)
        seq=[]; 
        for k in ['j','j','k','\x1b[B','\x1b[A']: seq.append(st(k,1))
        o2=st('\n',2)
        rec('picker: j,j,k,Down,Up,Enter','moves cursor, picks #2 (git stage) onto prompt', o2.strip().splitlines()[-1][-30:] if o2.strip() else 'nothing', o2.rstrip().endswith('git stage'))
        sh.send('\x03'); sh.read(1)
        st('redo\n',3); o=st('3',2)
        rec('picker: press 3','git stash on prompt', o.strip().splitlines()[-1][-30:] if o.strip() else 'nothing', o.rstrip().endswith('git stash'))
        sh.send('\x03'); sh.read(1)
        st('redo\n',3); o=st('q',2); o2=st('echo after\n')
        rec('picker: q','exits cleanly, nothing on prompt', (o.strip().splitlines() or [''])[-1][-40:], 'git st' not in o.strip().splitlines()[-1] if o.strip() else True)
        st('cdd src && ls\n'); o=st('redo\n'); o2=st('\n'); o3=st('pwd\n')
        rec('`cdd src && ls` -> redo -> Enter','cd src && ls runs, cwd=src', o.rstrip().splitlines()[-1][-30:]+' | pwd '+o3.strip().splitlines()[-2][-20:] if len(o3.strip().splitlines())>1 else o3, 'repo/src' in o3)
        st('cd ..\n')
        st('npm run tset\n'); o=st('redo\n',3); o2=st('\n',4)
        rec('`npm run tset` (hook) -> redo -> Enter','npm run test runs', o.rstrip().splitlines()[-1][-40:], 'npm run test' in o.splitlines()[-1] and '> echo test' in o2)
        st('ls READEM.md\n'); o=st('redo\n'); o2=st('\n')
        rec('`ls READEM.md` -> redo -> Enter','ls README.md', o.rstrip().splitlines()[-1][-40:], o.rstrip().endswith('ls README.md'))
        st("sh -c 'exit 3'\n"); o=st('redo\n')
        rec('opaque failure `sh -c exit 3`','no fix pushed, no re-run', o.strip().splitlines()[-1][-60:], 'QQP> sh -c' not in o)
    else:
        st('gti status\n'); o=st('redo\n'); o2=st('\x1b[A',1.5); o3=st('\n')
        rec('bash: `gti status` -> redo -> Up','fix in history; Up shows it; Enter runs', 'Up shows: '+(o2.strip()[-30:])+(' | ran' if 'On branch' in o3 else ''), 'git status' in o2 and 'On branch' in o3)
        st('echo ok\n'); o=st('redo\n')
        rec('bash: redo after success','not stale-as-new', 'shows old gti status' if 'gti status' in o else o[:60], 'gti status' not in o)
        st('git checkout develpo\n'); o=st('redo\n'); o2=st('\x1b[A',1.5); o3=st('\n')
        rec('bash: checkout typo -> redo -> Up -> Enter','git checkout develop', o2.strip()[-30:], "Switched to branch 'develop'" in o3)
        st('make biuld\n'); o=st('redo -y\n',3)
        rec('bash: redo -y safe','runs make build', 'ran' if 'building' in o else o[-80:], 'building' in o)
        st('git branch -d feature/auth\n'); o=st('redo -y\n',3); sh.send('\x03'); sh.read(1); o2=st('git branch --list feature/auth\n')
        rec('bash: redo -y destructive','not auto-run', 'kept' if 'feature/auth' in o2.split('--list feature/auth',1)[-1] else 'DELETED', 'feature/auth' in o2.split('--list feature/auth',1)[-1])
        st("redo run 'git sta'\n"); o=st('redo\n',3); o2=st('2',2); o3=st('\x1b[A',1.5)
        rec('bash: picker press 2 -> Up','git stage in history', o3.strip()[-30:], 'git stage' in o3)
    sh.close()
run('zsh'); run('bash')
print('\n\n==== SUMMARY ====')
for r in LOG: print(' | '.join(r))
