#!/bin/bash
. "$(dirname "$0")/lib.sh"
G='git init -q --bare ../remote.git; git init -q; echo hi > README.md; git add .; git commit -qm init; git remote add origin ../remote.git'
GP="$G; git push -qu origin main"
PKG='printf "{\"name\":\"x\",\"version\":\"1.0.0\",\"scripts\":{\"dev\":\"echo dev\",\"test\":\"echo t\",\"build\":\"echo b\"}}" > package.json'
tc prompt_literal "$G" '$ git status'
tc dry "$G" 'git git status'
tc hyphen_git 'git init -q' 'git-log'
tc hyphen_npm "$PKG" 'npm-install'
tc has_exists_script 'printf "#!/bin/sh\necho deployed\n" > deploy.sh; chmod +x deploy.sh' 'deploy.sh'
tc python_command_noexec 'printf "print(1)\n" > script.py' './script.py'
tc python_command_bare 'printf "print(1)\n" > script.py' 'script.py'
tc python_execute 'printf "print(1)\n" > foo.py' 'python3 foo'
tc cat_dir 'mkdir somedir' 'cat somedir'
tc grep_recursive 'mkdir somedir; echo foo > somedir/a.txt' 'grep foo somedir'
tc cp_omitting_dir 'mkdir srcdir; touch srcdir/a' 'cp srcdir dst'
tc rm_dir 'mkdir somedir; touch somedir/keep' 'rm somedir'
tc mkdir_p '' 'mkdir a/b/c'
tc touch_parent '' 'touch a/b/c.txt'
tc cd_mkdir '' 'cd newdir'
tc cd_correction_home 'mkdir -p $HOME/Desktop' 'cd ~/Dekstop'
tc cd_correction_mid 'mkdir -p projects/foo' 'cd projets/foo'
tc ln_s_order 'echo data > real.txt' 'ln -s link.txt real.txt'
tc chmod_x 'printf "#!/bin/sh\necho hi\n" > tool.sh' './tool.sh'
tc man_no_space '' 'mandiff'
tc long_form_help_javac '' 'javac -h'
tc long_form_help_sqlite '' 'sqlite3 -h'
MODES=run tc quote_echo '' "echo 'mixed\""
MODES=run tc quote_commit "$G; echo x >> README.md; git add ." "git commit -m 'it's broken'"
tc sl_ls 'touch a' 'sl'
tc no_command_vom 'touch notes.txt' 'vom notes.txt'
tc space_npminstall "$PKG" 'npminstall'
tc space_gitstatus "$G" 'gitstatus'
tc path_from_history 'mkdir -p $HOME/proj/app; echo "a: 1" > $HOME/proj/app/config.yml' 'cat config.yml' 'cat ~/proj/app/config.yml'
tc history_nearmiss "$G" 'git log --oneline --grahp --decorate --all' 'git log --oneline --graph --decorate --all'
tc git_add_commit_nothing "$G; echo more >> README.md" 'git commit -m update'
tc git_add_nosuch "$G" 'git add nosuchfile'
tc git_add_case "$G" 'git add Readme.md'
tc git_checkout_typo "$G; git branch feature-login" 'git checkout feature-logn'
tc git_checkout_new "$G" 'git checkout newthing'
tc git_branch_exists "$G" 'git checkout -b main'
tc git_push_noupstream "$GP; git checkout -qb feat" 'git push'
tc git_push_rejected "$GP; git clone -q ../remote.git ../c2; (cd ../c2; echo r > r; git add r; git commit -qm r; git push -q); echo l > l; git add l; git commit -qm l" 'git push'
tc git_pull_notracking "$GP; git checkout -qb feat" 'git pull'
tc git_stash_pop_conflict "$G; echo a >> README.md; git stash -q; echo b >> README.md; git commit -qam b; echo c >> README.md" 'git stash pop'
tc git_merge_unrelated "$G; mkdir ../o; (cd ../o; git init -q; echo o>o; git add .; git commit -qm o); git remote add other ../o; git fetch -q other" 'git merge other/main'
tc git_not_command "$G" 'git brnch'
tc git_two_dashes "$G" 'git log -oneline'
tc git_flag_after_filename "$G" 'git log README.md -p'
tc git_diff_staged "$G; echo z >> README.md; git add README.md" 'git diff --exit-code'
tc npm_missing_script "$PKG" 'npm run tset'
tc npm_run_script "$PKG" 'npm dev'
tc npm_wrong_command "$PKG" 'npm urgrade'
tc pip_unknown '' 'pip3 instal requests'
tc brew_unknown '' 'brew isntall wget'
python3 -m http.server 8799 --bind 127.0.0.1 >/dev/null 2>&1 & SRV=$!; sleep 1
tc port_in_use '' 'python3 -m http.server 8799 --bind 127.0.0.1'
kill $SRV
export GOCACHE=$QA/work/gocache GOPATH=$QA/work/gopath GOTOOLCHAIN=local GOPROXY=off GOFLAGS=-mod=mod
tc go_run 'printf "package main\nfunc main(){}\n" > main.go' 'go run main'
tc javac_noext 'printf "class Foo{public static void main(String[] a){}}\n" > Foo.java' 'javac Foo'
tc java_class 'printf "class Foo{public static void main(String[] a){}}\n" > Foo.java; javac Foo.java' 'java Foo.class'
